import assert from 'node:assert/strict';
import ts from 'typescript';
import { readFileSync } from 'node:fs';
const source = readFileSync(new URL('../app/deadline-utils.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2020 } }).outputText;
const { easternDate, weekBounds, deadlineStatus, filterDeadlines } = await import('data:text/javascript;base64,' + Buffer.from(js).toString('base64'));
assert.equal(easternDate(new Date('2026-08-31T03:59:59Z')), '2026-08-30');
assert.equal(easternDate(new Date('2026-08-31T04:00:00Z')), '2026-08-31');
assert.equal(easternDate(new Date('2026-11-02T04:59:59Z')), '2026-11-01');
assert.equal(easternDate(new Date('2026-11-02T05:00:00Z')), '2026-11-02');
assert.deepEqual(weekBounds('2026-10-01'), { start: '2026-09-28', end: '2026-10-04' });
assert.deepEqual(weekBounds('2026-12-06'), { start: '2026-11-30', end: '2026-12-06' });
const make = (id, due, complete = false) => ({ id, week: 1, title: id, due, complete });
const items = [make('past', '2026-09-27'), make('current', '2026-10-04'), make('future', '2026-10-11'), make('finished', '2026-09-27', true)];
for (const [filter, id] of [['This week','current'],['Overdue','past'],['Upcoming','future'],['Completed','finished']]) assert.deepEqual(filterDeadlines(items, filter, '2026-10-01').map((item) => item.id), [id]);
assert.equal(deadlineStatus(items[1], '2026-10-04'), 'Due soon');
assert.equal(deadlineStatus(items[1], '2026-10-05'), 'Overdue');
assert.equal(deadlineStatus(items[3], '2026-10-01'), 'Completed');
assert.equal(filterDeadlines(items.map((item) => ({ ...item, complete: true })), 'Overdue', '2026-12-07').length, 0);
assert.equal(filterDeadlines(items, 'This week', '2027-01-01').length, 0);
console.log('Deadline checks passed: Eastern midnight, daylight saving, weekly filters, completion, and end of term.');
